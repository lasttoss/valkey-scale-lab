#!/usr/bin/env python3
"""Generate docs/figures/valkey-scale-lab-flow.html.

Every number in it comes from docs/measurements.md, which is regenerated by `make measure` against
a real Valkey. If a number here stops matching the lab, this file is the thing that is wrong.

    python3 docs/figures/valkey-scale-lab-flow.generator.py
    python3 <diagram-design>/scripts/self_check.py docs/figures/valkey-scale-lab-flow.html
    make diagram
"""
import html
import pathlib

PAPER, INK, MUTED, ACCENT, LINE, TINT, BAD = "#f5f5f5", "#2d3142", "#4f5d75", "#b3541e", "#c9ccd1", "#fdf4ef", "#8c2f1f"
FONT = {"sans": "'Geist', system-ui, sans-serif",
        "mono": "'Geist Mono', ui-monospace, monospace",
        "serif": "'Instrument Serif', serif"}
ADVANCE = {"mono": 0.605, "sans": 0.525, "sans-bold": 0.565}
PAD, GAP, MARGIN = 16, 124, 24


def esc(s):
    return html.escape(str(s))


def width(s, size, family="sans", weight="400"):
    key = "mono" if family == "mono" else ("sans-bold" if weight == "600" else "sans")
    return len(s) * ADVANCE[key] * size


def text(x, y, s, size=12.5, weight="400", fill=INK, family="sans", anchor="start"):
    return (f'<text x="{x:.0f}" y="{y:.0f}" font-family="{FONT[family]}" font-size="{size}" '
            f'font-weight="{weight}" fill="{fill}" text-anchor="{anchor}">{esc(s)}</text>')


def rect(x, y, w, h, fill="#ffffff", stroke=LINE, rx=10):
    return f'<rect x="{x:.0f}" y="{y:.0f}" width="{w:.0f}" height="{h:.0f}" rx="{rx}" fill="{fill}" stroke="{stroke}"/>'


def arrow(x1, y1, x2, y2, label="", dashed=False):
    dash = ' stroke-dasharray="5 4"' if dashed else ""
    # A label wider than the gap between the endpoints is a label that covers a block: fail instead.
    if label:
        room = abs(x2 - x1) - 16
        need = width(label, 11, "mono") + 12
        if need > room:
            raise SystemExit(f"label {label!r} needs {need:.0f}px, the gap gives {room:.0f}px: shorten it")
    out = [f'<line x1="{x1:.0f}" y1="{y1:.0f}" x2="{x2:.0f}" y2="{y2:.0f}" stroke="{MUTED}" stroke-width="1.6" '
           f'marker-end="url(#arrowhead)"{dash}/>']
    if label:
        mx, my = (x1 + x2) / 2, (y1 + y2) / 2
        lw = width(label, 11, "mono") + 12
        out.append(rect(mx - lw / 2, my - 12, lw, 20, fill=PAPER, stroke="none", rx=5))
        out.append(text(mx, my + 2, label, size=11, fill=MUTED, family="mono", anchor="middle"))
    return "".join(out)


class Block:
    def __init__(self, title, subtitle, lines, tint=None):
        self.title, self.subtitle, self.lines, self.tint = title, subtitle, lines, tint
        widths = [width(title, 15, weight="600")]
        if subtitle:
            widths.append(width(subtitle, 11.5, "mono"))
        for line, mono in lines:
            widths.append(width(line, 11.5, "mono" if mono else "sans"))
        self.w = max(widths) + PAD * 2
        self.h = PAD * 2 + 22 + (16 if subtitle else 0) + len(lines) * 17

    def render(self, x, y):
        out = [rect(x, y, self.w, self.h, fill=self.tint or "#ffffff")]
        out.append(text(x + PAD, y + PAD + 12, self.title, size=15, weight="600"))
        yy = y + PAD + 34
        if self.subtitle:
            out.append(text(x + PAD, yy + 4, self.subtitle, size=11.5, fill=MUTED, family="mono"))
            yy += 16
        for line, mono in self.lines:
            out.append(text(x + PAD, yy + 9, line, size=11.5, family="mono" if mono else "sans"))
            yy += 17
        return "".join(out)


HANDLER = Block("the match handler", "one function, two versions of it", [
    ("600 live matches on one pod", False),
    ("the same work in both: PING + SET", False),
    ("per match. Only the client differs.", False),
    ("", False),
    ("nothing here is about load:", False),
    ("the command rate is the same in", False),
    ("both columns, and so is the game.", False),
])

LEAK = Block("what it was", "redis.NewClient inside the match", [
    ("300 matches:  3 -> 303", True),
    ("600 matches:  3 -> 500 (ceiling)", True),
    ("clients in this process     600", True),
    ("103 matches refused", True),
    ("server's words to the client:", False),
    ("  EOF", True),
    ("the server logged \"max number of", False),
    ("clients reached\"; the socket just", False),
    ("closed, which is why the search", False),
    ("for this started in the wrong place", False),
], tint="#fbf1ef")

FIX = Block("what it is now", "one client, cached by addr+db", [
    ("300 matches:  3 -> 4", True),
    ("600 matches:  3 -> 7", True),
    ("clients in this process       1", True),
    ("0 errors", True),
    ("PoolSize 16, MinIdleConns 2,", True),
    ("MaxActiveConns 16", True),
    ("PoolSize is not the ceiling: the", False),
    ("pool grows past it under load.", False),
    ("MaxActiveConns is the number that", False),
    ("bounds one pod.", False),
], tint=TINT)

WALK = Block("the same incident, one call later", "walking the keyspace, 200,600 keys", [
    ("KEYS  20 walks   571ms  cmdstat_keys 20", True),
    ("SCAN  20 walks  1.371s  cmdstat_keys  0", True),
    ("worst round trip another client saw:", False),
    ("  KEYS 18.7ms      SCAN 3.8ms", True),
    ("SCAN is the slower tool and the", False),
    ("better one: it moves the cost out of", False),
    ("one blocking call, so the stall a", False),
    ("player feels goes with it.", False),
], tint=TINT)

INSTRUMENT = Block("how it is measured", "the server's own INFO, plus one PING", [
    ("INFO clients: connected_clients,", True),
    ("  maxclients", True),
    ("INFO stats: total_connections_received", True),
    ("INFO commandstats: cmdstat_keys", True),
    ("a second client probes PING in a loop", False),
    ("and reports p50/p99/p99.9/max: the", False),
    ("claim is about everybody else, so it", False),
    ("is measured from somebody else", False),
])

CLAIMS = [
    ("the connection count was a function", "docs/measurements.md · make measure"),
    ("the fix is a cache key and a ceiling", "internal/hotpath/hotpath.go"),
    ("the gate fails when the numbers slip", "internal/hotpath/hotpath_test.go"),
]

col1, col2, col3 = HANDLER.w, max(LEAK.w, FIX.w, WALK.w), INSTRUMENT.w
total_w = col1 + col2 + col3 + GAP * 2 + MARGIN * 2
x1 = MARGIN
x2 = MARGIN + col1 + GAP
x3 = MARGIN + col1 + col2 + GAP * 2
y = MARGIN + 8
handler_y = y + 60
leak_y = y + 60
fix_y = leak_y + LEAK.h + 26
walk_y = fix_y + FIX.h + 26
instrument_y = leak_y
strip_y = max(handler_y + HANDLER.h, walk_y + WALK.h, instrument_y + INSTRUMENT.h) + 44
strip_h, H = 84, 0
H = strip_y + strip_h + MARGIN + 22

svg = [f'<svg viewBox="0 0 {total_w:.0f} {H:.0f}" role="img" aria-labelledby="fig-title fig-desc" xmlns="http://www.w3.org/2000/svg">']
svg.append('<title id="fig-title">valkey-scale-lab: a client per match, and what the fix costs</title>')
svg.append('<desc id="fig-desc">A match handler is shown in two versions with identical work. In the first, a redis client is created per '
           'match: 600 live matches produce 600 clients held open, 500 connections on the server because that is its maxclients, and 103 '
           'matches refused; the server logs "max number of clients reached" and the client only sees EOF. In the second, one client is '
           'cached by address and database with an explicit pool - PoolSize 16 and MaxActiveConns 16, the second being the actual ceiling - '
           'and the same 600 matches produce 7 connections and 0 errors. Below, the same server walked over 200,600 keys: KEYS in 20 walks '
           'takes 571 milliseconds with 20 blocking calls inside the server and the worst round trip another client saw is 18.7 milliseconds, '
           'while SCAN takes 1.371 seconds with no blocking call and the worst round trip is 3.8 milliseconds, which is the trade: SCAN is '
           'slower and it is the better tool. Measurement is by the server\'s own INFO, connected_clients, maxclients, '
           'total_connections_received and cmdstat_keys, plus a second client probing PING in a loop to report p50, p99, p99.9 and max.</desc>')
svg.append(f'<defs><marker id="arrowhead" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" '
           f'orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="{MUTED}"/></marker></defs>')

svg.append(HANDLER.render(x1, handler_y))
svg.append(LEAK.render(x2, leak_y))
svg.append(FIX.render(x2, fix_y))
svg.append(WALK.render(x2, walk_y))
svg.append(INSTRUMENT.render(x3, instrument_y))
svg.append(arrow(x1 + col1, handler_y + 40, x2, leak_y + 40, "-mode=leak"))
svg.append(arrow(x1 + col1, handler_y + 74, x2, fix_y + 40, "-mode=fixed"))

svg.append(rect(MARGIN, strip_y, total_w - MARGIN * 2, strip_h))
svg.append(text(MARGIN + PAD, strip_y + 26, "three sentences this repository is willing to be judged by, each with the file that answers for it",
                size=12.5, weight="600", fill=MUTED))
chip_w = (total_w - MARGIN * 2 - PAD * 2 - 24) / 3
for i, (claim, src) in enumerate(CLAIMS):
    if width(claim, 11.5) + 20 > chip_w:
        raise SystemExit(f"claim {i + 1} does not fit its chip: shorten it")
    cx = MARGIN + PAD + i * (chip_w + 12)
    svg.append(rect(cx, strip_y + 38, chip_w, strip_h - 50, fill="#ffffff", rx=8))
    svg.append(text(cx + 10, strip_y + 58, f"{i + 1}. {claim}", size=11.5, fill=INK))
    svg.append(text(cx + 10, strip_y + 74, src, size=10.5, fill=MUTED, family="mono"))

svg.append(text(MARGIN, H - 14, "make measure - reproduces every number in this figure against a real Valkey; the tables are written by the command, not by hand",
                size=11, fill=MUTED, family="mono"))
svg.append('</svg>')

meta = ('<!-- diagram-meta {"topic":"valkey-scale-lab-flow","level":"runtime","type":"data-flow",'
        '"question":"What does a Redis client per match cost, and what does the fix cost?",'
        '"sources":["internal/hotpath/hotpath.go","internal/keywalk/keywalk.go","internal/valkeyinfo/info.go",'
        '"internal/limits/limits.go","cmd/lab/main.go","docs/measurements.md","docker-compose.yml"],'
        '"updated":"2026-10-13"} -->')

page = f"""{meta}
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>valkey-scale-lab</title>
<link href="https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500;600&display=swap" rel="stylesheet">
<style>
  *, *::before, *::after {{ box-sizing: border-box; margin: 0; padding: 0; }}
  :root {{
    --color-paper: {PAPER}; --color-ink: {INK}; --color-muted: {MUTED}; --color-accent: {ACCENT};
    --font-sans: 'Geist', system-ui, sans-serif; --font-serif: 'Instrument Serif', serif;
    --font-mono: 'Geist Mono', ui-monospace, monospace;
  }}
  body {{ font-family: var(--font-sans); background: var(--color-paper); color: var(--color-ink);
         min-height: 100vh; display: flex; align-items: center; justify-content: center; padding: 3rem 2rem; }}
  .frame {{ max-width: {total_w + 40:.0f}px; width: 100%; }}
  .eyebrow {{ font-family: var(--font-mono); font-size: 0.66rem; font-weight: 500; letter-spacing: 0.18em;
              text-transform: uppercase; color: var(--color-muted); margin-bottom: 0.5rem; }}
  h1 {{ font-family: var(--font-serif); font-size: clamp(1.5rem, 2.4vw + 0.75rem, 2rem); font-weight: 400;
        letter-spacing: -0.02em; line-height: 1.15; color: var(--color-ink); margin-bottom: 1.5rem; }}
  .diagram-container {{ width: 100%; overflow-x: auto; }}
  svg {{ width: 100%; max-width: {total_w:.0f}px; display: block; }}
  .caption {{ font-family: var(--font-mono); font-size: 0.7rem; color: var(--color-muted); margin-top: 1rem; }}
</style>
</head>
<body>
<div class="frame">
  <p class="eyebrow">valkey-scale-lab · connections, pools and the walk</p>
  <h1>The same 600 matches, 500 connections or 7</h1>
  <div class="diagram-container">
{"".join(svg)}
  </div>
  <p class="caption">The two columns do the same work against the same server; only the client differs. 500 is the server's maxclients, so
  the first column is also the story of a limit being hit - and of why raising it is not the fix: at 10,000 the same pod holds 10,000 sockets
  and the wall moves. The second column is a cache key and a ceiling. Below it, the other half of the same incident: KEYS blocks the server
  for as long as the walk takes and every other client waits, which is what the 18.7ms is. SCAN takes twice as long overall and costs
  everyone else five times less.</p>
</div>
</body>
</html>
"""
out = pathlib.Path(__file__).with_name("valkey-scale-lab-flow.html")
out.write_text(page, encoding="utf-8")
print(f"wrote {out.name}: {total_w:.0f}x{H:.0f} viewBox, {len(page)} bytes")
